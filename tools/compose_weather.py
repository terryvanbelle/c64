def table(label, data):
    return label + ":\n" + "\n".join(
        "    .byte " + ",".join(f"${v:02x}" for v in data[i:i+16])
        for i in range(0, len(data), 16)) + "\n"


def periods(clock):
    return [round(clock / (SAMPLE_HZ * rate)) for rate in RATES]


def rate_for(contour, index, count, pace):
    position = index / max(1, count - 1)
    if contour == "question":
        shape = -.07 + .21 * position**1.7
    elif contour == "statement":
        shape = .055 - .16 * position
    elif contour == "arch":
        shape = -.025 + .10 * math.sin(position * math.pi) - .035 * position
    elif contour == "insist":
        shape = (.055, -.025, .025)[index % 3] - .055 * position
    else:
        shape = 0
    desired = min(RATES[-1], max(RATES[0], pace + shape))
    return min(range(32), key=lambda i: abs(RATES[i] - desired))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    bank = json.loads((OUT / "voice.json").read_text())
    units = bank if isinstance(bank, list) else bank["fragments"]
    by_name = {unit["name"]: unit for unit in units}
    records, report_sections, spoken = [], [], []
    tick = 0

    def event(sample_id, duration, rate, mouth, energy, section, name):
        nonlocal tick
        assert 1 <= duration <= 255
        records.append([sample_id, duration, rate, mouth, energy, section])
        spoken.append(dict(tick=tick, name=name, duration=duration, rate_index=rate))
        tick += duration

    for si, (name, phrases) in enumerate(SECTIONS):
        start = tick
        for phrase in phrases:
            words = [word.split("-") for word in phrase.words.split()]
            count = sum(map(len, words))
            index = 0
            for wi, syllables in enumerate(words):
                for ji, syllable in enumerate(syllables):
                    unit = by_name[syllable]
                    rate = rate_for(phrase.contour, index, count, phrase.pace)
                    # Use the slower actual regional rate to leave enough
                    # time for every nibble, plus one sequencer-tick margin.
                    hz = min(clock / periods(clock)[rate] for clock in (PAL, NTSC))
                    duration = math.ceil(unit["samples"] / hz * 100) + 1
                    if ji == len(syllables) - 1 and wi < len(words) - 1:
                        duration += 7 if phrase.contour != "insist" else 3
                    event(unit["id"], duration, rate, unit["mouth"],
                          unit["energy"], si, syllable)
                    index += 1
            event(0xfe, phrase.after, 16, 0, 0, si, "pause")
        report_sections.append(dict(name=name, start_seconds=start / 100,
                                    seconds=(tick-start) / 100, phrases=len(phrases)))
    # $FF terminates; the renderer leaves the mouth at rest.
    encoded = bytes(x for record in records for x in record) + bytes([0xff, 0, 0, 0, 0, 0])
    (OUT / "score.bin").write_bytes(encoded)
    (OUT / "score.inc").write_text(
        f"SONG_TICKS = {tick}\nSCORE_BYTES = {len(encoded)}\n"
        '.segment "RODATA"\nscore_data:\n    .incbin "score.bin"\nscore_end:\n')
    tables = ['.segment "RODATA"\n']
    for model, clock in (("pal", PAL), ("ntsc", NTSC)):
        latches = [p-1 for p in periods(clock)]
        tables.append(table(f"sample_timer_{model}_lo", [p & 255 for p in latches]))
        tables.append(table(f"sample_timer_{model}_hi", [p >> 8 for p in latches]))
    (OUT / "rate.inc").write_text("\n".join(tables))
    report = dict(title="A Mouthful of Weather", score_seconds=tick/100,
                  startup_settle_seconds=.2, ticks=tick, records=len(records),
                  syllables=sum(r[0] < 0xfe for r in records), score_bytes=len(encoded),
                  sample_hz=SAMPLE_HZ, min_pal_period=min(periods(PAL)),
                  sections=report_sections)
    (OUT / "composition.json").write_text(json.dumps(report, indent=2) + "\n")
    (OUT / "phrases.json").write_text(json.dumps(spoken, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
